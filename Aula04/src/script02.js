// Operadores de Atribuição

// Operador Atribuidor de Adição
let a = 5;
a += 10; // É o mesmo que a = a + 10;
console.log(a);

console.log(" ");

// Operador Atribuidor de Subtração
let b = 90;
b -= 50; // É o mesmo que b = b - 50;
console.log(b);

console.log(" ");

// Operador Atribuidor de Multiplicação
let c = 20;
c *= 10; //É o mesmo que c = c * 100;
console.log(c);

console.log(" ");

// Operador Atribuidor de Divisão
let d = 10;
d /= 5; // É o mesmo que d = d / 5;
console.log(d);

console.log(" ");

// Operador Atribuidor de Exponenciação
let e = 50;
e **= 2; // É o mesmo que e = e ** 2;
console.log(e);

console.log(" ");

// Operador Atribuidor de Resto
let f = 10;
f %= 5; // É o mesmo que e = e % 5;
console.log(f);

console.log(" ");

