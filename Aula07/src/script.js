// Exercício 1: Soma de valores informados pelo usuário
alert("Insira dois valores para somá-los.");

let valor1 = parseFloat(prompt("Insira o primeiro valor: "));
let valor2 = parseFloat(prompt("Insira o segundo valor: "));
let resultadoSoma = valor1 + valor2;

alert("O resultado da soma dos valores é: " + resultadoSoma);