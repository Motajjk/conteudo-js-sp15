// Exercício 6: Calculando área de retângulo
alert("Área de retângulo");

let alturaRetangulo = parseFloat(prompt("Informe a altura do retângulo em metros: "));
let larguraRetangulo = parseFloat(prompt("Informe a largura do retângulo em metros: "));
let areaRetangulo = alturaRetangulo * larguraRetangulo;

alert("A área total do retangulo de altura " + alturaRetangulo + "m e largura " + larguraRetangulo + "m é: " + areaRetangulo + "m²");