// Exercício 7: Calculando área do triângulo
alert("Área de triângulo");

let alturaTriangulo = parseFloat(prompt("Informe a altura do triângulo em metros: "));
let larguraTriangulo = parseFloat(prompt("Informe a largura do triângulo em metros: "));
let areaTriangulo = alturaTriangulo * larguraTriangulo / 2;

alert("A área do triângulo é: " + areaTriangulo + "m");